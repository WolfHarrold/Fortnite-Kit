// Build the Loot Terminal page and the paste-ready Worker.
//   node ui/build.mjs
// Outputs:
//   dist/loot-terminal.html   one self-contained page (host anywhere, or open the artifact)
//   worker/page.generated.js  the page as a JS string, served by the Worker at "/"
//   dist/worker.js            ONE file to paste into the Cloudflare dashboard editor

import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const p = (rel) => fileURLToPath(new URL(`../${rel}`, import.meta.url));
mkdirSync(p('dist'), { recursive: true });

const app = await build({
  entryPoints: [p('ui/app.js')],
  bundle: true, format: 'iife', write: false, target: 'es2020', legalComments: 'none',
});
const js = app.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = readFileSync(p('ui/template.html'), 'utf8').replace('/*APP*/', () => js);

writeFileSync(p('dist/loot-terminal.html'), html);
writeFileSync(p('worker/page.generated.js'), `// Generated by ui/build.mjs. Do not edit.\nexport default ${JSON.stringify(html)};\n`);

await build({
  entryPoints: [p('worker/worker.js')],
  bundle: true, format: 'esm', target: 'es2022', outfile: p('dist/worker.js'), legalComments: 'none',
  banner: { js: '// fortnite-kit Worker + Loot Terminal page. Paste this whole file into the Cloudflare editor.\n// Add the secret FORTNITE_API_COM_KEY in Settings > Variables and Secrets.' },
});

console.log(`page ${(html.length / 1024).toFixed(1)} KB -> dist/loot-terminal.html, worker -> dist/worker.js`);
